"""Цветовая гармония: оценка уместности цвета вещи под цветотип и палитру вкуса.

У каждой вещи есть цвет (строка). У человека — цветотип (весна/лето/осень/зима)
и палитра вкуса (StyleProfile.palette). `color_score` даёт числовой балл: чем выше,
тем лучше цвет подходит цветотипу и попадает в желаемую палитру. Composer выбирает
вещь в каждом слоте по этому баллу (цена — тай-брейк).

Правила — упрощённая колористика: у каждого цветотипа своя палитра; тёплый цвет для
холодного цветотипа (лето/зима) штрафуется и наоборот; базовые нейтральные подходят
почти всем и получают лёгкий плюс.
"""
from __future__ import annotations

# Рекомендованные тона по цветотипам (ключевые слова, нижний регистр).
SEASON_COLORS: dict[str, set[str]] = {
    "зима": {"чёрный", "белый", "синий", "изумруд", "красный", "серый", "фуксия"},
    "лето": {"серо-голубой", "голубой", "синий", "лавандовый", "серый", "белый",
             "пудровый", "сиреневый"},
    "весна": {"бежевый", "коралловый", "персиковый", "золотистый", "мятный",
              "жёлтый", "тёплый зелёный"},
    "осень": {"хаки", "терракота", "терракотовый", "горчичный", "коричневый",
              "оливковый", "бежевый", "рыжий"},
}

# Тёплые / холодные — для штрафа за конфликт подтона.
WARM = {"коралловый", "персиковый", "золотистый", "горчичный", "терракота",
        "терракотовый", "рыжий", "бежевый", "коричневый", "хаки", "оливковый", "жёлтый"}
COOL = {"серо-голубой", "голубой", "синий", "лавандовый", "сиреневый", "изумруд",
        "фуксия", "пудровый"}

# Универсальные базовые (подходят почти всем — слабый плюс, не мешают).
NEUTRALS = {"чёрный", "белый", "серый", "бежевый"}

# Холодные цветотипы (для них тёплые цвета — конфликт подтона).
_COOL_SEASONS = {"лето", "зима"}


def _tokens(color: str) -> set[str]:
    """«серо-голубой» -> {«серо-голубой», «серо», «голубой»} для гибкого сравнения."""
    c = (color or "").strip().lower()
    parts = {c} | set(c.replace("-", " ").split())
    return {p for p in parts if p}


def _expand(colors: set[str]) -> set[str]:
    out: set[str] = set()
    for c in colors:
        out |= _tokens(c)
    return out


def make_scorer(color_type: str | None, palette: list[str] | None):
    """Скорер с предвычисленными наборами токенов.

    Composer сортирует кандидатов в каждом слоте по цвету, то есть скорер зовётся
    O(n) раз на запрос — палитры цветотипа/вкуса раскрываем в токены один раз здесь,
    а не на каждую вещь.
    """
    season_toks = _expand(SEASON_COLORS.get(color_type, set())) if color_type else set()
    palette_toks = _expand(set(palette)) if palette else set()
    cool_type = color_type in _COOL_SEASONS if color_type else False

    def score(item_color: str) -> float:
        toks = _tokens(item_color)
        s = 0.0
        if color_type:
            if toks & season_toks:
                s += 2.0
            # Штраф за конфликт подтона: тёплый цвет холодному цветотипу и наоборот.
            if cool_type and (toks & WARM):
                s -= 1.5
            if (not cool_type) and (toks & COOL):
                s -= 1.5
        if toks & palette_toks:
            # Палитра ВКУСА (из фото-референсов) весит больше палитры цветотипа:
            # правила — мягкий приор, устойчивый вкус пользователя главнее (trend-rules-yield).
            s += 3.0
        if toks & NEUTRALS:
            s += 0.3
        return s

    return score


def color_score(item_color: str, color_type: str | None, palette: list[str] | None) -> float:
    """Балл уместности цвета для одиночного вызова (обёртка над make_scorer)."""
    return make_scorer(color_type, palette)(item_color)
